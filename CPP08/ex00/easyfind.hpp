#pragma once

#include <iostream>
#include <algorithm>
#include <stdexcept>
#include <list>
#include <vector>

template <typename T>
typename T::iterator easyfind(T& container, int value)
{
    typename T::iterator it = std::find(container.begin(), container.end(), value);

    if (it == container.end())
        throw std::runtime_error("Integer not found");

    return it;
};
